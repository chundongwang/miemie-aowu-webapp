#!/usr/bin/env node
// One-shot generator: reads the chinese-idiom-db CSV and emits a chunked
// INSERT migration into migrations/0019_seed_idioms.sql.
//
// Run once locally:
//   node scripts/generate-idiom-seed.mjs /Users/chundong/Downloads/chinese-idiom-db-master/chinese-idioms-12976.txt
//
// Then apply migrations with:
//   npx wrangler d1 migrations apply miemie-aowu-db --local
//   npx wrangler d1 migrations apply miemie-aowu-db --remote

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const inputPath = process.argv[2];
if (!inputPath) {
  console.error("usage: node generate-idiom-seed.mjs <path-to-csv>");
  process.exit(1);
}

const outputPath = resolve(process.cwd(), "migrations/0019_seed_idioms.sql");
const CHUNK_SIZE = 50;

// Each CSV line is comma-separated with each field optionally wrapped in
// double quotes. The data has no embedded ASCII commas or escaped quotes
// (verified by inspection), so a simple split is safe.
function parseCsvLine(line) {
  const fields = line.split(",");
  return fields.map((f) => {
    if (f.length >= 2 && f[0] === '"' && f[f.length - 1] === '"') {
      return f.slice(1, -1);
    }
    return f;
  });
}

function sqlEscape(s) {
  if (s == null || s === "") return "NULL";
  return "'" + s.replace(/'/g, "''") + "'";
}

const lines = readFileSync(inputPath, "utf8").split(/\r?\n/).filter((l) => l.length > 0);
const rows = [];
for (const line of lines) {
  const f = parseCsvLine(line);
  if (f.length < 4) continue;
  const [idStr, idiom, pinyin, explanation, origin, example] = f;
  const id = Number(idStr);
  if (!Number.isFinite(id) || !idiom || !pinyin) continue;
  rows.push({
    id,
    idiom,
    pinyin: pinyin.replace(/\s+/g, " ").trim(),
    explanation: explanation || null,
    origin: origin || null,
    example: example || null,
  });
}

console.log(`Parsed ${rows.length} idiom rows from ${inputPath}`);

const out = [];
out.push("-- Migration: 0019_seed_idioms");
out.push("-- Generated by scripts/generate-idiom-seed.mjs — do not edit by hand.");
out.push(`-- ${rows.length} idiom rows.`);
out.push("");

for (let i = 0; i < rows.length; i += CHUNK_SIZE) {
  const chunk = rows.slice(i, i + CHUNK_SIZE);
  const values = chunk
    .map(
      (r) =>
        `(${r.id}, ${sqlEscape(r.idiom)}, ${sqlEscape(r.pinyin)}, ${sqlEscape(r.explanation)}, ${sqlEscape(r.origin)}, ${sqlEscape(r.example)})`
    )
    .join(",\n  ");
  out.push(
    `INSERT OR IGNORE INTO idioms (id, idiom, pinyin, explanation, origin, example) VALUES\n  ${values};`
  );
  out.push("");
}

writeFileSync(outputPath, out.join("\n"));
console.log(`Wrote ${outputPath}`);
